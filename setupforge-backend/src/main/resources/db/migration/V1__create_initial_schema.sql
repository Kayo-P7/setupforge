DO $$
DECLARE
    proximo_id BIGINT := 1;
BEGIN
    IF to_regclass('public.categoria_tb_seq') IS NULL THEN
        IF to_regclass('public.categoria_tb') IS NOT NULL THEN
            EXECUTE 'SELECT COALESCE(MAX(id), 0) + 1 FROM public.categoria_tb'
                INTO proximo_id;
        END IF;

        EXECUTE format(
            'CREATE SEQUENCE public.categoria_tb_seq START WITH %s INCREMENT BY 50',
            proximo_id
        );
    ELSE
        ALTER SEQUENCE public.categoria_tb_seq INCREMENT BY 50;
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS categoria_tb (
    id BIGINT NOT NULL DEFAULT nextval('public.categoria_tb_seq') PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS produto_tb (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(1000),
    marca VARCHAR(100) NOT NULL,
    preco NUMERIC(10, 2) NOT NULL,
    imagem_url VARCHAR(500),
    categoria_id BIGINT NOT NULL REFERENCES categoria_tb (id)
);

CREATE INDEX IF NOT EXISTS idx_produto_categoria_id ON produto_tb (categoria_id);

CREATE TABLE IF NOT EXISTS setup_tb (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(1000),
    orcamento NUMERIC(10, 2) NOT NULL,
    tipo_montagem VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_setup_produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setup_id BIGINT NOT NULL REFERENCES setup_tb (id),
    produto_id BIGINT NOT NULL REFERENCES produto_tb (id),
    quantidade INTEGER,
    preco_unitario NUMERIC(38, 2)
);

CREATE INDEX IF NOT EXISTS idx_setup_produtos_setup_id ON tb_setup_produtos (setup_id);
CREATE INDEX IF NOT EXISTS idx_setup_produtos_produto_id ON tb_setup_produtos (produto_id);
